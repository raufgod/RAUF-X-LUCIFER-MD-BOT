'use strict';
// AI conversation mode + voice for AI commands.
//
//  1) Send .gpt (or .deepseek, .gemini ...) once. Every answer the AI gives is remembered. After that you do NOT need the
//     command again: just REPLY (swipe / "reply") to ANY AI answer and the same AI answers again, with its chat history.
//  2) Voice: reply to an AI answer with a voice note, or reply to any voice note with ".gpt" (any AI command).
//     This needs the user's own Groq API key (pasted on the website when linking, or sent with  .aikey gsk_...).
//     The voice is converted to text by Groq Whisper and the answer is generated by Groq in the background.
//     The answer comes back as a VOICE NOTE (Microsoft Edge neural voice, same engine as the welcome voice agent), text if voice fails.
//     Without a key, voice messages to AI are not processed.
const fs = require('fs');
const path = require('path');

const STATE_DIR = path.resolve(process.env.AI_STATE_DIR || path.join(__dirname, '..', 'state'));       // NOT inside data/ (that folder is redirected per session)
const KEYS_FILE = path.join(STATE_DIR, 'ai-keys.json');
const REPLIES_FILE = path.join(STATE_DIR, 'ai-replies.json');
const TTL = 7 * 24 * 3600e3, MAX_TRACKED = 1500;
const GROQ = 'https://api.groq.com/openai/v1';
const CHAT_MODEL = () => process.env.AI_VOICE_MODEL || 'llama-3.3-70b-versatile';
const STT_MODEL = () => process.env.AI_STT_MODEL || 'whisper-large-v3-turbo';
const NAMES = { gpt: 'ChatGPT', gemini: 'Gemini', deepseek: 'DeepSeek', asyntai: 'Asyntai', talkai: 'TalkAI', notegpt: 'NoteGPT', zonerai: 'ZonerAI', pollinationai: 'Pollination AI', mathgpt: 'MathGPT' };
const aliasOf = (n) => (n === 'chatgpt' ? 'gpt' : n === 'deepseekai' ? 'deepseek' : n);

// ───────────────────────── tiny JSON store ─────────────────────────
function readJson(file, def) { try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch (_) { return def; } }
function writeJson(file, obj) { try { fs.mkdirSync(STATE_DIR, { recursive: true }); fs.writeFileSync(file + '.tmp', JSON.stringify(obj), { mode: 0o600 }); fs.renameSync(file + '.tmp', file); } catch (e) { console.error('[ai-session] save failed:', e.message); } }

// ───────────────────────── Groq keys (per linked number) ─────────────────────────
const idOf = (sock) => String(sock?.__ownerNumber || 'main');
const validKey = (k) => /^gsk_[A-Za-z0-9_-]{20,200}$/.test(String(k || '').trim());
function getKey(sock) {
  const k = readJson(KEYS_FILE, {})[idOf(sock)];
  if (k) return String(k);
  return idOf(sock) === 'main' ? String(process.env.GROQ_API_KEY || '') : '';   // the main bot may use the server's own key
}
function setKey(id, key) { const all = readJson(KEYS_FILE, {}); if (key) all[String(id)] = String(key).trim(); else delete all[String(id)]; writeJson(KEYS_FILE, all); }
const mask = (k) => (k ? k.slice(0, 4) + '…' + k.slice(-4) : '');

// Live check used by the website: 401/403 = wrong key. Any network problem is not the user's fault, so the key is accepted.
async function checkKey(key) {
  if (!validKey(key)) return { ok: false, error: 'That does not look like a Groq API key. It starts with gsk_ (get one free at console.groq.com/keys).' };
  try {
    const r = await fetch(GROQ + '/models', { headers: { Authorization: 'Bearer ' + key }, signal: AbortSignal.timeout(8000) });
    if (r.status === 401 || r.status === 403) return { ok: false, error: 'Groq says this API key is not valid. Please copy it again from console.groq.com/keys.' };
  } catch (_) { /* offline check failed: accept */ }
  return { ok: true };
}

// ───────────────────────── which AI wrote which message ─────────────────────────
let replies = null, saveTimer = null;
function load() { if (!replies) { replies = readJson(REPLIES_FILE, {}); prune(); } return replies; }
function prune() {
  const now = Date.now(); const keys = Object.keys(replies);
  for (const k of keys) if (now - (replies[k].t || 0) > TTL) delete replies[k];
  const left = Object.keys(replies); if (left.length > MAX_TRACKED) left.sort((a, b) => replies[a].t - replies[b].t).slice(0, left.length - MAX_TRACKED).forEach((k) => delete replies[k]);
}
function persist() { if (saveTimer) return; saveTimer = setTimeout(() => { saveTimer = null; prune(); writeJson(REPLIES_FILE, replies); }, 3000); saveTimer.unref?.(); }
const rk = (sock, chatId, id) => `${sock?.__sessionKey || 'main'}|${chatId}|${id}`;
/** Remember that message `sent` (returned by sock.sendMessage) is an answer of AI `provider`. */
function track(sock, chatId, sent, provider) {
  try { const id = sent?.key?.id; if (!id) return; load()[rk(sock, chatId, id)] = { p: aliasOf(provider), t: Date.now() }; persist(); } catch (_) {}
}
const lookup = (sock, chatId, id) => (id ? load()[rk(sock, chatId, id)] || null : null);
const hkeyOf = (chatId, message, provider) => `wa:${chatId}:${(message && message.key && (message.key.participant || message.key.remoteJid)) || chatId}:${provider}`;

// ───────────────────────── helpers ─────────────────────────
function ctxOf(msg) {
  const m = msg || {};
  return (m.extendedTextMessage || m.audioMessage || m.imageMessage || m.videoMessage || m.documentMessage || {}).contextInfo || null;
}
function textOf(msg) { return String(msg?.conversation || msg?.extendedTextMessage?.text || '').trim(); }
const footer = () => '\n\n*© RAUF × LUCIFER*\n*Powered by RAUF × LUCIFER*';
const head = () => { try { return `*${require('../settings').botName} AI*\n\n`; } catch (_) { return '*AI*\n\n'; } };
const noticeAt = new Map();
async function notice(sock, chatId, message, text, tag) {
  const k = chatId + '|' + tag, now = Date.now();
  if (now - (noticeAt.get(k) || 0) < 10 * 60e3) return;            // do not nag
  noticeAt.set(k, now);
  await sock.sendMessage(chatId, { text }, { quoted: message }).catch(() => {});
}
const NO_KEY = '🎙️ *Voice to AI needs a Groq API key.*\n\nAdd yours once:\n• on the website (Link WhatsApp page → "AI API key"), or\n• send  *.aikey gsk_xxxxxxxx*  here (free key: console.groq.com/keys)\n\nUntil then, please type your question as text.';

// ───────────────────────── Groq: speech -> text, and the answer ─────────────────────────
async function transcribe(buf, mime, key) {
  const fd = new FormData();
  fd.append('file', new Blob([buf], { type: mime || 'audio/ogg' }), 'voice.ogg');
  fd.append('model', STT_MODEL()); fd.append('response_format', 'json'); fd.append('temperature', '0');   // language is detected automatically
  const r = await fetch(GROQ + '/audio/transcriptions', { method: 'POST', headers: { Authorization: 'Bearer ' + key }, body: fd, signal: AbortSignal.timeout(40000) });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) { const e = new Error('STT ' + r.status + ' ' + String(j?.error?.message || '').slice(0, 120)); e.status = r.status; throw e; }
  return String(j.text || '').trim();
}
async function groqAnswer(provider, text, history, key) {
  const name = NAMES[provider] || 'AI';
  const messages = [{ role: 'system', content: `You are ${name}, a helpful AI assistant chatting on WhatsApp. Reply in the same language and script the user used (Hindi in Devanagari stays Devanagari, Hinglish stays Hinglish). Be clear and reasonably short (under 250 words). Use light WhatsApp formatting only (*bold*, short lines).` }];
  for (const h of history.slice(-14)) messages.push({ role: h.r === 'u' ? 'user' : 'assistant', content: h.t });
  messages.push({ role: 'user', content: text });
  const r = await fetch(GROQ + '/chat/completions', {
    method: 'POST', headers: { Authorization: 'Bearer ' + key, 'Content-Type': 'application/json' },
    body: JSON.stringify({ model: CHAT_MODEL(), messages, temperature: 0.7, max_tokens: 900 }), signal: AbortSignal.timeout(45000)
  });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) { const e = new Error('GROQ ' + r.status + ' ' + String(j?.error?.message || '').slice(0, 120)); e.status = r.status; throw e; }
  const out = String(j?.choices?.[0]?.message?.content || '').trim();
  if (!out) throw new Error('GROQ empty answer');
  return out;
}

async function downloadAudio(audioMessage) {
  const { downloadContentFromMessage } = require('@whiskeysockets/baileys');
  const stream = await downloadContentFromMessage(audioMessage, 'audio');
  const chunks = []; let size = 0;
  for await (const c of stream) { size += c.length; if (size > 8 * 1024 * 1024) throw new Error('TOO_BIG'); chunks.push(c); }
  return Buffer.concat(chunks);
}

// ───────────────────────── answer as a voice note (Microsoft Edge neural voice) ─────────────────────────
function langOf(t) {
  const s = String(t || '');
  if (/[\u0900-\u097F]/.test(s)) return 'hi';
  if (/[\u0980-\u09FF]/.test(s)) return 'bn';
  if (/[\u0600-\u06FF]/.test(s)) return 'ur';
  if (/[\u3040-\u30FF]/.test(s)) return 'ja';
  if (/[\uAC00-\uD7AF]/.test(s)) return 'ko';
  if (/[\u4E00-\u9FFF]/.test(s)) return 'zh';
  return 'en';
}
function forSpeech(t, max) {
  let s = String(t || '').replace(/```[\s\S]*?```/g, ' ').replace(/[*_`#>~|]+/g, '').replace(/\p{Extended_Pictographic}/gu, '').replace(/\s*\n+\s*/g, '. ').replace(/\s+/g, ' ').trim();
  if (s.length <= max) return { text: s, cut: false };
  const part = s.slice(0, max), i = Math.max(part.lastIndexOf('।'), part.lastIndexOf('.'), part.lastIndexOf('?'), part.lastIndexOf('!'));
  return { text: i > max * 0.5 ? part.slice(0, i + 1) : part, cut: true };
}
const asText = (answer) => ({ text: head() + String(answer).slice(0, 6500) + footer() });
/** Sends the answer as a voice note (Edge TTS). Falls back to normal AI-style text if voice cannot be made. */
async function sendAnswer(sock, chatId, message, answer, provider, asVoice) {
  if (asVoice && String(process.env.AI_VOICE_REPLY || 'voice').toLowerCase() !== 'text') {
    try {
      const TTS = require('./callAgent/tts');
      const sp = forSpeech(answer, TTS.MAX_CHARS || 1500);
      const audio = await TTS.synth(sp.text, { lang: langOf(sp.text) });
      try { await sock.sendPresenceUpdate('recording', chatId); } catch (_) {}
      const sent = await sock.sendMessage(chatId, { audio, mimetype: 'audio/ogg; codecs=opus', ptt: true }, { quoted: message, noCard: true });
      track(sock, chatId, sent, provider);                                 // replying to this voice answer continues the chat too
      if (sp.cut) await sock.sendMessage(chatId, asText(answer), { quoted: message }).then((m) => track(sock, chatId, m, provider)).catch(() => {});   // long answer: full text as well
      return sent;
    } catch (e) { console.error('[ai-voice] voice reply failed, sending text instead:', String(e.message || e).slice(0, 120)); }
  }
  const sent = await sock.sendMessage(chatId, asText(answer), { quoted: message });
  track(sock, chatId, sent, provider);
  return sent;
}

/** A voice note is addressed to AI `provider`: transcribe it, answer it (Groq), send the answer like a normal AI answer. */
async function voiceToAI(sock, chatId, message, audioMessage, provider) {
  provider = aliasOf(provider);
  const key = getKey(sock);
  if (!key) return notice(sock, chatId, message, NO_KEY, 'nokey');
  if ((audioMessage.seconds || 0) > 180) return sock.sendMessage(chatId, { text: '🎙️ That voice note is too long. Please keep it under 3 minutes.' }, { quoted: message }).catch(() => {});
  try { await sock.sendPresenceUpdate('composing', chatId); } catch (_) {}
  const AI = require('./aiChat');
  const hkey = hkeyOf(chatId, message, provider);
  let said, answer;
  try {
    const buf = await downloadAudio(audioMessage);
    said = await transcribe(buf, audioMessage.mimetype, key);
    if (!said) return sock.sendMessage(chatId, { text: '🎙️ I could not hear anything in that voice note. Please try again.' }, { quoted: message }).catch(() => {});
    try { answer = await groqAnswer(provider, said, AI.hist(hkey), key); }
    catch (e) {
      if (e.status === 401 || e.status === 403) throw e;
      console.error('[ai-voice] Groq answer failed, trying the AI itself:', e.message);
      const out = await AI.ask(provider, hkey, said);                 // fallback: the chosen AI's own text service (records history itself)
      return sendAnswer(sock, chatId, message, out, provider, true);
    }
  } catch (e) {
    console.error('[ai-voice]', e.message);
    const bad = e.status === 401 || e.status === 403;
    return sock.sendMessage(chatId, { text: bad ? '⚠️ Your Groq API key was rejected. Send a fresh one with  *.aikey gsk_xxxxxxxx*' : e.message === 'TOO_BIG' ? '🎙️ That voice note is too big.' : '⚠️ Could not process the voice note right now. Please try again in a moment.' }, { quoted: message }).catch(() => {});
  }
  AI.record(hkey, said, answer);
  return sendAnswer(sock, chatId, message, answer, provider, true);
}

// ───────────────────────── hook 1: someone replied to an AI answer ─────────────────────────
// Returns true when the message was handled (main.js then stops processing it).
async function handleReply(sock, message, { rawText } = {}) {
  const msg = message?.message; if (!msg) return false;
  const ci = ctxOf(msg); const quotedId = ci?.stanzaId; if (!quotedId) return false;
  const chatId = message.key.remoteJid;
  const hit = lookup(sock, chatId, quotedId); if (!hit) return false;
  const text = String(rawText || textOf(msg) || '').trim();
  if (text.startsWith('.')) return false;                              // a real command: normal routing
  if (msg.audioMessage) { await voiceToAI(sock, chatId, message, msg.audioMessage, hit.p); return true; }
  if (!text) return false;                                             // image/sticker etc.: ignore
  const { callApi } = require('./kingApiClient');
  await callApi(hit.p, text, sock, chatId, message);                   // same path as ".gpt <text>": history, header, tracking
  return true;
}

// ───────────────────────── hook 2: ".gpt" sent as a reply to a voice note ─────────────────────────
function quotedAudio(message) {
  const q = ctxOf(message?.message)?.quotedMessage;
  return q?.audioMessage || q?.ephemeralMessage?.message?.audioMessage || null;
}
async function commandOnVoice(sock, chatId, message, provider) {
  const audio = quotedAudio(message); if (!audio) return false;
  await voiceToAI(sock, chatId, message, audio, provider); return true;
}

// ───────────────────────── .aikey ─────────────────────────
const parseCommand = (raw) => { const m = /^\.aikey(?:\s+(\S+))?\s*$/i.exec(String(raw || '').trim()); return m ? { arg: m[1] || '' } : null; };
async function runCommand(sock, message, cmd) {
  const chatId = message.key.remoteJid, id = idOf(sock), arg = cmd.arg.trim();
  const del = () => sock.sendMessage(chatId, { delete: message.key }).catch(() => {});   // remove the message that contains the key
  if (!arg || /^(status|info)$/i.test(arg)) {
    const k = getKey(sock);
    return k ? `🔑 AI voice key: *active* (${mask(k)})\nChange: *.aikey gsk_...*   Remove: *.aikey remove*` : '🔑 No Groq key set. Voice messages to AI will not work.\nSend *.aikey gsk_xxxxxxxx*  (free key: console.groq.com/keys)';
  }
  if (/^(remove|off|delete|clear)$/i.test(arg)) { setKey(id, ''); return '🔑 Groq key removed. Voice messages to AI are off.'; }
  const c = await checkKey(arg);
  if (!c.ok) { del(); return '❌ ' + c.error; }
  setKey(id, arg); del();
  return '✅ Groq key saved. Now reply to any AI answer with a voice note, or reply to a voice note with *.gpt*.\n_(I tried to delete your message that contained the key.)_';
}

