
async function pairCommand(sock, chatId, message, q) {
    const settings = require('../settings');
    const text = `🔐 *${settings.botName} Pairing*\n\n` +
        `Pairing code is generated by the bot host during first startup.\n` +
        `Open your hosting console and follow the pairing instructions there.\n\n` +
        `For security, this command does not send your phone number to any third-party pairing server.`;
    return sock.sendMessage(chatId, { text }, { quoted: message });
}

module.exports = pairCommand; 